-- Transactional outbox of the PMS notifications. A notification is written in the same transaction as the task it
-- reports, then sent by a relay that keeps it until the PMS has received it:
-- - the PMS is never told a room is clean if the transaction that marked it clean rolled back
-- - the PMS is told eventually, even if it is down or the application stops right after the commit
CREATE TABLE pms_notification
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- One notification per task: a task cannot report its room clean twice
    task_id    BIGINT                   NOT NULL UNIQUE REFERENCES cleaning_task (id),
    room_id    BIGINT                   NOT NULL REFERENCES room (id),
    cleaned_at TIMESTAMP WITH TIME ZONE NOT NULL,
    attempts   INT                      NOT NULL DEFAULT 0,
    sent_at    TIMESTAMP WITH TIME ZONE,
    last_error VARCHAR(500)
);

-- The relay only reads the notifications still to send
CREATE INDEX idx_pms_notification_pending ON pms_notification (id) WHERE sent_at IS NULL;
