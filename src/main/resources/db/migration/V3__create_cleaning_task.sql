-- Targets of the composite foreign keys below: they let the database itself guarantee that a task, its room and its
-- assignee all belong to the same establishment
ALTER TABLE room
    ADD CONSTRAINT uk_room_id_establishment UNIQUE (id, establishment_id);
ALTER TABLE staff
    ADD CONSTRAINT uk_staff_id_establishment UNIQUE (id, establishment_id);

CREATE TABLE cleaning_task
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    establishment_id BIGINT                   NOT NULL REFERENCES establishment (id),
    room_id          BIGINT                   NOT NULL,
    assignee_id      BIGINT,
    scheduled_on     DATE                     NOT NULL,
    status           VARCHAR(20)              NOT NULL,
    comment          VARCHAR(500),
    created_by       VARCHAR(50)              NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    started_at       TIMESTAMP WITH TIME ZONE,
    done_at          TIMESTAMP WITH TIME ZONE,
    version          BIGINT                   NOT NULL DEFAULT 0,
    CONSTRAINT fk_cleaning_task_room FOREIGN KEY (room_id, establishment_id)
        REFERENCES room (id, establishment_id),
    -- Not checked while assignee_id is null (MATCH SIMPLE): a task can be planned before being assigned
    CONSTRAINT fk_cleaning_task_assignee FOREIGN KEY (assignee_id, establishment_id)
        REFERENCES staff (id, establishment_id),
    -- The times always match the status: no task done without having been started
    CONSTRAINT ck_cleaning_task_status CHECK (
        (status = 'TODO' AND started_at IS NULL AND done_at IS NULL)
            OR (status = 'IN_PROGRESS' AND started_at IS NOT NULL AND done_at IS NULL)
            OR (status = 'DONE' AND started_at IS NOT NULL AND done_at IS NOT NULL))
);

-- "Never two cleaning tasks open on the same accommodation", race-proof: two managers planning the same room at the
-- same time both pass any check made in Java, only one insert passes this index. The open statuses are listed rather
-- than "<> 'DONE'", so that a status added later is not open by accident. This is the only definition of an open task.
CREATE UNIQUE INDEX uk_cleaning_task_one_open_per_room ON cleaning_task (room_id)
    WHERE status IN ('TODO', 'IN_PROGRESS');

-- "Several hundred tasks a day": the tasks of a day, optionally by status, and the tasks by status
CREATE INDEX idx_cleaning_task_establishment_day ON cleaning_task (establishment_id, scheduled_on, status);
CREATE INDEX idx_cleaning_task_establishment_status ON cleaning_task (establishment_id, status);

-- PostgreSQL does not index foreign keys: without these, the history of a room, the tasks of an employee and the
-- checks made when a room or an employee is deleted would scan the whole table
CREATE INDEX idx_cleaning_task_room ON cleaning_task (room_id);
CREATE INDEX idx_cleaning_task_assignee ON cleaning_task (assignee_id);
